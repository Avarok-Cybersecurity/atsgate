//! `eval --write | --check`: downloads pinned evaluation data into `.cache/eval`, scores the
//! gazetteer and the title normalizer, splices the numbers into docs/evaluation.md, and writes
//! the small licensed samples under tests/fixtures/eval that the regression tests read offline.

mod skillspan;
mod talentclef;
mod techwolf;
#[cfg(test)]
mod tests;

use crate::fetch;
use crate::{Mode, root, sync_file};
use atsgate_taxonomy::{Gazetteer, Taxonomy};

pub const SKILLSPAN_URL: &str = "https://raw.githubusercontent.com/kris927b/SkillSpan/\
2ccf3de5b5af7a5409b8dd814fb1315dd6e0ae1b/data/json/test.json";
pub const SKILLSPAN_SHA256: &str =
    "8438eda34939a5877b984ea5daf9e6ff39b2d5c7e3d73cca0499d3de3784d24a";
pub const TECHWOLF_URL: &str = "https://huggingface.co/datasets/TechWolf/\
Synthetic-ESCO-skill-sentences/resolve/09fc487d1394c1fdfd224cb621a89b14af925716/dataset.csv";
pub const TECHWOLF_SHA256: &str =
    "3217976eeb08e196cc740868a1a2b03e7cfc5897adcf8c9262e1a40a73144393";
pub const TALENTCLEF_URL: &str = "https://zenodo.org/api/records/15292308/files/TaskA.zip/content";
pub const TALENTCLEF_SHA256: &str =
    "2ebd5202661f17620e4c3900dcf565a28277b29fdca6478e1713dbf516b4cddf";

/// Every n-th SkillSpan sentence / TechWolf row goes into the committed sample.
pub const SKILLSPAN_SAMPLE_EVERY: usize = 10;
pub const TECHWOLF_SAMPLE_EVERY: usize = 100;

pub const SAMPLE_DIR: &str = "tests/fixtures/eval";
const DOC: &str = "docs/evaluation.md";
const BEGIN: &str =
    "<!-- eval:begin (generated by `cargo run -p xtask -- eval --write`; do not edit) -->";
const END: &str = "<!-- eval:end -->";
const TASK_A_FILES: [&str; 3] = ["queries", "corpus_elements", "qrels.tsv"];

fn pct(n: usize, d: usize) -> String {
    if d == 0 {
        "n/a".into()
    } else {
        format!("{:.1}%", 100.0 * n as f64 / d as f64)
    }
}

pub fn render(
    spans: &[(String, skillspan::Counts)],
    tw: &techwolf::Counts,
    tc: &talentclef::Scores,
) -> String {
    let mut out = String::from(
        "### SkillSpan test split: gazetteer spans vs. skill + knowledge annotations\n\n\
         | subset | gold spans | predicted | precision (exact) | recall (exact) | precision (overlap) | recall (overlap) |\n\
         |---|---|---|---|---|---|---|\n",
    );
    for (name, c) in spans {
        out.push_str(&format!(
            "| {name} | {} | {} | {} | {} | {} | {} |\n",
            c.gold,
            c.predicted,
            pct(c.exact, c.predicted),
            pct(c.exact, c.gold),
            pct(c.predicted_overlapping, c.predicted),
            pct(c.gold_overlapped, c.gold),
        ));
    }
    out.push_str(&format!(
        "\n### TechWolf synthetic ESCO skill sentences: is the target skill found?\n\n\
         | sentences | target resolvable | recall (same concept) | recall (same, broader or narrower) | predictions | precision (lower bound) |\n\
         |---|---|---|---|---|---|\n\
         | {} | {} | {} | {} | {} | {} |\n",
        tw.sentences,
        tw.resolvable,
        pct(tw.found_exact, tw.resolvable),
        pct(tw.found_related, tw.resolvable),
        tw.predicted,
        pct(tw.predicted_target, tw.predicted),
    ));
    out.push_str(&format!(
        "\n### TalentCLEF 2025 Task A, English validation: job-title normalization\n\n\
         | queries | resolved to an occupation | MAP (taxonomy) | MAP (folded-string baseline) | MAP (ESCO only; leaks gold labels) |\n\
         |---|---|---|---|---|\n\
         | {} | {} | {:.3} | {:.3} | {:.3} |\n",
        tc.queries,
        pct(tc.resolved, tc.queries),
        tc.map,
        tc.string_baseline_map,
        tc.esco_only_map,
    ));
    out
}

fn every_nth_line(text: &str, n: usize, keep_header: bool) -> String {
    let mut out: String = text
        .lines()
        .enumerate()
        .filter(|(i, _)| (keep_header && *i == 0) || (i % n == usize::from(keep_header)))
        .map(|(_, l)| format!("{l}\n"))
        .collect();
    if out.is_empty() {
        out.push('\n');
    }
    out
}

fn task_a_files(zip_bytes: &[u8]) -> Result<Vec<(String, String)>, String> {
    let mut archive =
        zip::ZipArchive::new(std::io::Cursor::new(zip_bytes)).map_err(|e| e.to_string())?;
    TASK_A_FILES
        .iter()
        .map(|name| {
            let path = format!("validation/english/{name}");
            let mut file = archive.by_name(&path).map_err(|e| format!("{path}: {e}"))?;
            let mut text = String::new();
            std::io::Read::read_to_string(&mut file, &mut text).map_err(|e| e.to_string())?;
            Ok(((*name).to_owned(), text))
        })
        .collect()
}

pub fn run(mode: Mode) -> Result<(), String> {
    let taxonomy = Taxonomy::builtin().map_err(|e| e.to_string())?;
    let gazetteer = Gazetteer::skills(taxonomy);
    let cache = |name: &str| fetch::cache_dir(&["eval", name]);
    let ss = fetch::pinned(
        SKILLSPAN_URL,
        SKILLSPAN_SHA256,
        &cache("skillspan-test.json"),
    )?;
    let tw = fetch::pinned(TECHWOLF_URL, TECHWOLF_SHA256, &cache("techwolf.csv"))?;
    let tc = fetch::pinned(
        TALENTCLEF_URL,
        TALENTCLEF_SHA256,
        &cache("talentclef-TaskA.zip"),
    )?;
    let ss_text = String::from_utf8(ss).map_err(|_| "SkillSpan is not UTF-8")?;
    let tw_text = String::from_utf8(tw).map_err(|_| "TechWolf is not UTF-8")?;
    let task_a = task_a_files(&tc)?;
    let spans = skillspan::evaluate(&skillspan::parse(&ss_text)?, &gazetteer);
    let tw_counts = techwolf::evaluate(&techwolf::parse(tw_text.as_bytes())?, &gazetteer);
    let split = talentclef::parse(&task_a[0].1, &task_a[1].1, &task_a[2].1);
    let tc_scores = talentclef::evaluate(&split, taxonomy);
    let table = render(&spans, &tw_counts, &tc_scores);
    let doc_path = root().join(DOC);
    let doc = std::fs::read_to_string(&doc_path).map_err(|e| format!("{DOC}: {e}"))?;
    let (head, rest) = doc
        .split_once(BEGIN)
        .ok_or(format!("{DOC} lacks {BEGIN}"))?;
    let (_, tail) = rest.split_once(END).ok_or(format!("{DOC} lacks {END}"))?;
    let updated = format!("{head}{BEGIN}\n{table}{END}{tail}");
    sync_file(&doc_path, updated.as_bytes(), mode)?;
    let sample = |name: &str| root().join(SAMPLE_DIR).join(name);
    sync_file(
        &sample("skillspan-test-sample.jsonl"),
        every_nth_line(&ss_text, SKILLSPAN_SAMPLE_EVERY, false).as_bytes(),
        mode,
    )?;
    sync_file(
        &sample("techwolf-sample.csv"),
        every_nth_line(&tw_text, TECHWOLF_SAMPLE_EVERY, true).as_bytes(),
        mode,
    )?;
    for (name, text) in &task_a {
        let path = sample(&format!("talentclef-taskA-en-validation/{name}"));
        sync_file(&path, text.as_bytes(), mode)?;
    }
    Ok(())
}

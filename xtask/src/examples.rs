//! `examples --write | --check`: generated blueprints under `blueprints/examples/`, regenerated
//! from the job descriptions under `tests/fixtures/jd/` so the committed copies cannot drift
//! from the generator.

use atsgate_blueprint::generate::{GenerateOptions, generate};
use atsgate_taxonomy::{Gazetteer, Scope, Taxonomy};

pub struct Example {
    pub fixture: &'static str,
    pub output: &'static str,
    pub id: &'static str,
}

pub const EXAMPLES: [Example; 1] = [Example {
    fixture: "tests/fixtures/jd/artcraft-hn-2026-11-02.txt",
    output: "blueprints/examples/artcraft-senior-engineer.yaml",
    id: "artcraft-senior-engineer",
}];

/// The description below a fixture's `---` source header.
pub fn fixture_body(text: &str) -> Result<&str, String> {
    text.split_once("\n---\n")
        .map(|(_, body)| body)
        .ok_or("fixture lacks a `---` line after its source header".into())
}

pub fn all() -> Result<Vec<(String, Vec<u8>)>, String> {
    let taxonomy = Taxonomy::builtin().map_err(|e| e.to_string())?;
    let gazetteer = Gazetteer::new(taxonomy, Scope::Postings);
    EXAMPLES
        .iter()
        .map(|e| {
            let text = std::fs::read_to_string(crate::root().join(e.fixture))
                .map_err(|err| format!("{}: {err}", e.fixture))?;
            let options = GenerateOptions {
                id: e.id.to_owned(),
                version: "0.1.0".to_owned(),
                occupational_category: None,
            };
            let blueprint = generate(fixture_body(&text)?, &options, &gazetteer)
                .map_err(|err| format!("{}: {err}", e.fixture))?;
            let yaml = blueprint.to_yaml().map_err(|err| err.to_string())?;
            let header = format!(
                "# Generated by `cargo run -p xtask -- examples --write` from {}.\n\
                 # provenance.reviewed is false: a person must review it before it gates anything.\n",
                e.fixture
            );
            Ok((e.output.to_owned(), format!("{header}{yaml}").into_bytes()))
        })
        .collect()
}

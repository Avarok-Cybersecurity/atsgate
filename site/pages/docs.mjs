// The docs index, the evaluation page (rendered from docs/evaluation.md) and the 404 page.
import { graph } from '../lib/html.mjs';
import { evaluation } from '../lib/data.mjs';
import { render } from '../lib/md.mjs';

export const DOCS = [
  ['/docs/scoring/', 'Scoring formulas and vendor floors', 'The seven dimensions, the vendor σ and floor table and every parse penalty, generated from the scorer.'],
  ['/docs/blueprint-spec/', 'Job blueprint specification', 'Every blueprint field, generated from the JSON Schema.'],
  ['/docs/career-and-tailoring/', 'Career file and tailoring', 'One career file, many tailored resumes, none able to add a fact.'],
  ['/docs/action/', 'GitHub Action reference', 'Inputs, outputs, modes, the CLI and binary verification.'],
  ['/docs/fairness/', 'Fairness: what ATSGate never reads', 'Protected inputs, the metamorphic tests and the integrity flags.'],
  ['/docs/vendors/', 'Simulated vendor profiles', 'What each vendor’s documentation says and why the results are simulated.'],
  ['/docs/evaluation/', 'Evaluation', 'Measured precision and recall of the taxonomy matcher and the generator.'],
  ['/docs/faq/', 'Frequently asked questions', 'Short answers to the common questions.'],
];

export function docsIndex() {
  const body = `
<h2 id="pages">What is in the documentation?</h2>
<ul>
${DOCS.map(([href, title, what]) => `<li><a href="${href}">${title}</a>: ${what}</li>`).join('\n')}
</ul>
<h2 id="model">How is ATSGate built?</h2>
<p>ATSGate is a Rust workspace of pure crates that take bytes and return values: extraction, resume parsing, the career format, blueprints, the O*NET and ESCO taxonomy, scoring and rendering. Only the <code>atsgate</code> command reads files or the network, and the GitHub Action wraps it. Tables on these pages that describe the code are generated from it, and CI fails when they drift.</p>`;
  const page = {
    route: '/docs/',
    title: 'ATSGate documentation',
    description: 'ATSGate documentation: scoring, the blueprint spec, career and tailoring files, the GitHub Action, fairness, vendors, evaluation and FAQ.',
    lede: 'How ATSGate scores a resume, what a blueprint contains, how the career file renders resumes, and what the action takes and returns.',
    body,
  };
  return { ...page, jsonld: graph(page) };
}

export function evaluationPage() {
  const body = `<p>Rendered from <a href="https://github.com/Avarok-Cybersecurity/atsgate/blob/main/docs/evaluation.md">docs/evaluation.md</a>, whose numbers are regenerated by <code>cargo run -p xtask -- eval --write</code> from datasets pinned by revision and sha256.</p>
${render(evaluation.markdown, { caption: (h) => h || 'Evaluation results' })}`;
  const page = {
    route: '/docs/evaluation/',
    type: 'TechArticle',
    title: 'Evaluation: taxonomy and blueprint generator · ATSGate',
    h1: 'Evaluation of the taxonomy and generator',
    description: 'Measured precision, recall and MAP of the ATSGate skill gazetteer and title normalizer on SkillSpan, TechWolf ESCO sentences and TalentCLEF 2025.',
    lede: 'How well the dictionary matcher behind blueprints finds skills and titles, on public datasets, with the limits stated plainly.',
    body,
  };
  return { ...page, jsonld: graph(page) };
}

export function notFound() {
  const body = `<h2 id="where">Where should I look instead?</h2>
<p>Start from the <a href="/">ATSGate home page</a>, the <a href="/docs/">documentation</a> or the list of <a href="/blueprints/">built-in blueprints</a>.</p>`;
  const page = {
    route: '/404.html',
    title: 'Page not found · ATSGate',
    description: 'This page does not exist on ats.express. Start from the ATSGate home page, the documentation or the built-in blueprints.',
    lede: 'ATSGate could not find that page. It may have moved when the documentation was reorganised.',
    body,
  };
  return { ...page, jsonld: graph(page) };
}
